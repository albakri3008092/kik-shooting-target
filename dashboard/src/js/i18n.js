window.KIK_LANG = localStorage.getItem('kik.lang') || 'ms';
window.t = (k) => (window.KIK_I18N[window.KIK_LANG] && window.KIK_I18N[window.KIK_LANG][k]) || k;
window.setLang = (code) => {
  window.KIK_LANG = code;
  localStorage.setItem('kik.lang', code);
  document.documentElement.lang = code === 'ms' ? 'ms' : 'en';
  document.querySelectorAll('[data-i]').forEach(el => {
    const k = el.getAttribute('data-i'); el.textContent = window.t(k);
  });
  document.querySelectorAll('[data-ip]').forEach(el => {
    const k = el.getAttribute('data-ip'); el.placeholder = window.t(k);
  });
  // Notify the app so it can re-render dynamic content
  window.dispatchEvent(new CustomEvent('langchange'));
};
